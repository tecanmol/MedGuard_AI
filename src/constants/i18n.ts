const translations: Record<Language, typeof en> = { en, hi };

// ── Accessor ────────────────────────────────────────────────────────

export type TranslationSection = keyof typeof en;

/**
 * Look up a translated string.
 *
 * @param lang  — current language code
 * @param section — screen/section key (e.g. `'dashboard'`)
 * @param key — string key within that section
 * @returns translated string, or English fallback, or the raw key
 */
export function t(
  lang: Language,
  section: TranslationSection,
  key: string,
): string {
  const sectionStrings = translations[lang]?.[section] as
    | Record<string, string>
    | undefined;
  if (sectionStrings?.[key]) return sectionStrings[key];

  // Fallback to English
  const enStrings = translations.en[section] as
    | Record<string, string>
    | undefined;
  return enStrings?.[key] ?? key;
}

/**
 * Returns all strings for a section in the given language.
 */
export function tSection(
  lang: Language,
  section: TranslationSection,
): Record<string, string> {
  return (translations[lang]?.[section] ?? translations.en[section]) as Record<
    string,
    string
  >;
}

