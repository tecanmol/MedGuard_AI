    "# CELL 5 — Dual-Branch Architecture (Texture + Structure)\n",
    "def build_dual_branch_model():\n",
    "    inputs = tf.keras.Input(shape=(IMG_SIZE, IMG_SIZE, 3))\n",
    "    \n",
    "    # FAIRNESS AUGMENTATION: Forces model to ignore lighting/skin color and focus on lesion structure\n",
    "    x_aug = tf.keras.layers.RandomFlip('horizontal_and_vertical')(inputs)\n",
    "    x_aug = tf.keras.layers.RandomRotation(0.2)(x_aug)\n",
    "    x_aug = tf.keras.layers.RandomZoom(0.2)(x_aug)\n",
    "    x_aug = tf.keras.layers.RandomContrast(0.2)(x_aug)\n",
    "    x_aug = tf.keras.layers.RandomBrightness(0.2)(x_aug)\n",
    "\n",
    "    # BRANCH 1: EfficientNetB0 (Global Structural Features)\n",
    "    # Note: EffNet expects [0, 255] which x_aug provides.\n",
    "    eff_base = tf.keras.applications.EfficientNetB0(input_shape=(IMG_SIZE, IMG_SIZE, 3), include_top=False, weights='imagenet')\n",
    "    eff_base.trainable = False\n",
    "    eff_out = eff_base(x_aug, training=False)  # Frozen BN stats\n",
    "    eff_out = tf.keras.layers.GlobalAveragePooling2D()(eff_out)\n",
    "    \n",
    "    # BRANCH 2: ResNet50V2 (Local Textural Features)\n",
    "    # Note: ResNet50V2 expects [-1, 1], so we explicitly preprocess it here.\n",
    "    x_res = tf.keras.applications.resnet_v2.preprocess_input(tf.identity(x_aug))\n",
    "    res_base = tf.keras.applications.ResNet50V2(input_shape=(IMG_SIZE, IMG_SIZE, 3), include_top=False, weights='imagenet')\n",
    "    res_base.trainable = False\n",
    "    res_out = res_base(x_res, training=False)\n",
    "    res_out = tf.keras.layers.GlobalAveragePooling2D()(res_out)\n",
    "    \n",
    "    # FUSION\n",
    "    fused = tf.keras.layers.Concatenate()([eff_out, res_out])\n",
    "    \n",
    "    # CLASSIFICATION HEAD\n",
    "    x = tf.keras.layers.BatchNormalization()(fused)\n",
    "    x = tf.keras.layers.Dropout(0.4)(x)\n",
    "    x = tf.keras.layers.Dense(256, activation='relu')(x)\n",
    "    x = tf.keras.layers.Dropout(0.3)(x)\n",
    "    outputs = tf.keras.layers.Dense(5, activation='softmax')(x)\n",
    "    \n",
    "    model = tf.keras.Model(inputs, outputs)\n",
    "    return model, eff_base, res_base\n",
