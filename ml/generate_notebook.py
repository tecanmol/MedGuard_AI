    "# CELL 8 — XAI: Grad-CAM++ Visualizer\n",
    "def make_gradcam_plus_plus(img_array, model, layer_name):\n",
    "    grad_model = tf.keras.models.Model(model.inputs, [model.get_layer(layer_name).output, model.output])\n",
    "    \n",
    "    with tf.GradientTape() as tape3:\n",
    "        with tf.GradientTape() as tape2:\n",
    "            with tf.GradientTape() as tape1:\n",
    "                conv_outs, preds = grad_model(img_array)\n",
    "                pred_idx = tf.argmax(preds[0])\n",
    "                class_channel = preds[:, pred_idx]\n",
    "            grads = tape1.gradient(class_channel, conv_outs)\n",
    "        d2 = tape2.gradient(grads, conv_outs)\n",
    "    d3 = tape3.gradient(d2, conv_outs)\n",
    "\n",
    "    global_sum = tf.reduce_sum(conv_outs, axis=(0, 1, 2))\n",
    "    alpha_num = d2\n",
    "    alpha_denom = d2 * 2.0 + d3 * global_sum\n",
    "    alpha_denom = tf.where(alpha_denom != 0.0, alpha_denom, tf.ones_like(alpha_denom))\n",
    "    alphas = alpha_num / alpha_denom\n",
    "    \n",
    "    weights = tf.maximum(grads, 0.0)\n",
    "    alphas_thresholding = tf.where(weights, alphas, 0.0)\n",
    "    linear_weights = tf.reduce_sum(alphas_thresholding * weights, axis=(0, 1))\n",
    "    \n",
    "    heatmap = tf.reduce_sum(tf.multiply(linear_weights, conv_outs[0]), axis=-1)\n",
    "    heatmap = tf.maximum(heatmap, 0) / tf.math.reduce_max(heatmap)\n",
    "    return heatmap.numpy()\n",
    "\n",
    "print(\"Generating XAI Interpretability Maps for Clinical Trust...\")\n",
    "sample_imgs = val_df[val_df['fitzpatrick'] >= 4].head(3) # Test on medium/dark skin\n",
